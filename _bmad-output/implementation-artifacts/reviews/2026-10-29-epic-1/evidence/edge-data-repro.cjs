const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const base = '/workspace/inquello/desktop';
const { DataService } = require(base + '/dist/main/data/service.js');
const { parsePolicy } = require(base + '/dist/main/data/policy.js');
const { governedRoots } = require(base + '/dist/main/data/inventory.js');
const { ExportJournal } = require(base + '/dist/main/data/journal.js');
const { exportData, exportedFilePath } = require(base + '/dist/main/data/export.js');
const { ClaudeKeyVault } = require(base + '/dist/main/providers/claude-vault.js');
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'inquello-edge-data-'));
  const userData = path.join(dir, 'profile');
  const roots = governedRoots(userData, path.join(dir, 'logs'));
  const policy = parsePolicy(fs.readFileSync(base + '/data-policy.json', 'utf8'));
  const journal = new ExportJournal(userData);
  for (const root of Object.values(roots)) fs.mkdirSync(root, { recursive: true });
  const vault = new ClaudeKeyVault({ safeStorage: { isEncryptionAvailable: () => false }, platform: 'linux', dir: path.join(userData, 'providers') });
  vault.save({ version: 1, key: 'sk-ant-synthetic-for-review-only', state: 'verified' });
  const service = new DataService({ load: { ok: true, policy }, roots, journal, runtime: { stop: async () => {}, start: async () => {}, activeTasks: () => 0 }, identity: { principal: async () => null, holdsSession: () => false, signOut: async () => ({ ok: true }), forgetLocally() {} }, chooseExportDestination: async () => null, chooseImportSource: async () => null, clearBrowserProfile: async () => {}, appVersion: 'review', runtimeVersion: 'review', logger: { info() {}, warn() {}, error() {} } });
  const deletion = await service.deleteData(['claude-key-vault']);
  console.log(JSON.stringify({ case: 'memory-only Claude deletion', deletion, keyStillHeld: vault.load() !== null }, null, 2));
  const secretFile = path.join(roots['runtime-home'], 'auth.json');
  const sentinel = '{"api_key":"SYNTHETIC_SECRET_SENTINEL"}';
  fs.writeFileSync(secretFile, sentinel);
  fs.mkdirSync(path.join(roots['runtime-home'], 'sessions'), { recursive: true });
  fs.symlinkSync(secretFile, path.join(roots['runtime-home'], 'sessions', 'linked.jsonl'));
  const destination = path.join(dir, 'export');
  const exported = await exportData({ policy, roots, destination, journal, attribution: { principal: null, appVersion: 'review', runtimeVersion: 'review' } });
  const copied = fs.readFileSync(exportedFilePath(destination, 'runtime-home', 'sessions/linked.jsonl'), 'utf8');
  console.log(JSON.stringify({ case: 'export symlink', exportedCategory: exported.manifest.included.find(x => x.files.some(f => f.path === 'sessions/linked.jsonl')).category, credentialsCopied: copied === sentinel, sourceWasSymlink: fs.lstatSync(path.join(roots['runtime-home'], 'sessions/linked.jsonl')).isSymbolicLink() }, null, 2));
  fs.rmSync(dir, { recursive: true, force: true });
})().catch(error => { console.error(error); process.exitCode = 1; });
